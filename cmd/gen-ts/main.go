// gen-ts writes the TypeScript copies of the wire types in internal/protocol
// to client/src/generated, one file per type, the way the client imports them
// (import type { Me } from "@/generated/Me").
//
//	go run ./cmd/gen-ts            # from the repository root
//
// The Go types are the single source of truth: structs and string enums are
// read by reflection, doc comments from the source, and unions from the
// protocol.Unions table that also drives the JSON codec. CI regenerates the
// files and fails if the committed copy differs.
package main

import (
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"reflect"
	"slices"
	"sort"
	"strings"
	"time"

	"github.com/rmx-lt/rmx-backend-probe/internal/protocol"
)

const header = "// Generated by cmd/gen-ts from internal/protocol. Do not edit by hand.\n"

func main() {
	out := flag.String("out", "client/src/generated", "directory for the .ts files")
	src := flag.String("src", "internal/protocol", "directory of the Go protocol package (for doc comments)")
	flag.Parse()

	docs, err := loadDocs(*src)
	if err != nil {
		fatal(err)
	}
	g := &generator{docs: docs, names: map[reflect.Type]string{}, files: map[string]string{}}
	if err := g.generate(); err != nil {
		fatal(err)
	}
	if err := write(*out, g.files); err != nil {
		fatal(err)
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "gen-ts:", err)
	os.Exit(1)
}

// write puts the files in dir and removes generated files that are no longer produced.
func write(dir string, files map[string]string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(dir, name+".ts"), []byte(content), 0o644); err != nil {
			return err
		}
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		name, ok := strings.CutSuffix(e.Name(), ".ts")
		if _, produced := files[name]; !ok || produced {
			continue
		}
		path := filepath.Join(dir, e.Name())
		if data, err := os.ReadFile(path); err == nil && strings.Contains(string(data), "Do not edit") {
			if err := os.Remove(path); err != nil {
				return err
			}
		}
	}
	return nil
}

// ---- Doc comments ------------------------------------------------------------

type docs struct {
	types  map[string]string // Go type name -> doc
	fields map[string]string // "Type.Field" -> doc
}

func loadDocs(dir string) (*docs, error) {
	d := &docs{types: map[string]string{}, fields: map[string]string{}}
	paths, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}
	fset := token.NewFileSet()
	for _, path := range paths {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		file, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}
			for _, spec := range gen.Specs {
				ts := spec.(*ast.TypeSpec)
				doc := ts.Doc
				if doc == nil && len(gen.Specs) == 1 {
					doc = gen.Doc
				}
				if doc != nil {
					d.types[ts.Name.Name] = strings.TrimSpace(doc.Text())
				}
				if st, ok := ts.Type.(*ast.StructType); ok {
					for _, f := range st.Fields.List {
						if f.Doc == nil {
							continue
						}
						for _, n := range f.Names {
							d.fields[ts.Name.Name+"."+n.Name] = strings.TrimSpace(f.Doc.Text())
						}
					}
				}
			}
		}
	}
	return d, nil
}

// ---- Generator -----------------------------------------------------------------

type generator struct {
	docs  *docs
	names map[reflect.Type]string // Go type -> TypeScript name, for the types that get a file
	files map[string]string       // TypeScript name -> file content
}

var timeType = reflect.TypeFor[time.Time]()

func (g *generator) generate() error {
	for _, e := range protocol.Enums {
		g.names[e.Type] = e.Name
	}
	for _, t := range protocol.Structs {
		g.names[t] = t.Name()
	}
	for _, u := range protocol.Unions {
		g.names[unionType(u)] = u.Name
	}

	for _, e := range protocol.Enums {
		quoted := make([]string, len(e.Values))
		for i, v := range e.Values {
			quoted[i] = fmt.Sprintf("%q", v)
		}
		g.add(e.Name, e.Type.Name(), nil, "export type "+e.Name+" = "+strings.Join(quoted, " | ")+";\n")
	}
	for _, t := range protocol.Structs {
		deps := map[string]bool{}
		body, err := g.object(t, t.Name(), "", deps, "")
		if err != nil {
			return err
		}
		g.add(t.Name(), t.Name(), deps, "export type "+t.Name()+" = "+body+";\n")
	}
	for _, u := range protocol.Unions {
		deps := map[string]bool{}
		var b strings.Builder
		b.WriteString("export type " + u.Name + " =\n")
		for _, v := range u.Variants {
			body, err := g.object(v.Type, v.Type.Name(), u.Tag, deps, v.Tag)
			if err != nil {
				return err
			}
			b.WriteString("  | " + strings.ReplaceAll(strings.TrimRight(body, "\n"), "\n", "\n  ") + "\n")
		}
		g.add(u.Name, u.Name, deps, strings.TrimRight(b.String(), "\n")+";\n")
	}
	return nil
}

// unionType is the Go wrapper struct of a union (Request for the "Request" union).
func unionType(u *protocol.Union) reflect.Type {
	for _, t := range []reflect.Type{
		reflect.TypeFor[protocol.Request](), reflect.TypeFor[protocol.RpcResult](), reflect.TypeFor[protocol.RpcData](),
		reflect.TypeFor[protocol.ServerMessage](),
	} {
		if t.Name() == u.Name {
			return t
		}
	}
	panic("no Go type for union " + u.Name)
}

func (g *generator) add(name, goName string, deps map[string]bool, body string) {
	var b strings.Builder
	b.WriteString(header)
	names := make([]string, 0, len(deps))
	for d := range deps {
		if d != name {
			names = append(names, d)
		}
	}
	sort.Strings(names)
	for _, d := range names {
		fmt.Fprintf(&b, "import type { %s } from \"./%s\";\n", d, d)
	}
	b.WriteString("\n")
	if doc := g.docs.types[goName]; doc != "" {
		b.WriteString(comment("", doc))
	}
	b.WriteString(body)
	g.files[name] = b.String()
}

// object renders a struct as a TypeScript object type. For a union variant,
// tag is the name of the tag member and tagValue its value.
func (g *generator) object(t reflect.Type, goName, tag string, deps map[string]bool, tagValue string) (string, error) {
	var b strings.Builder
	b.WriteString("{\n")
	if tag != "" {
		fmt.Fprintf(&b, "  %q: %q,\n", tag, tagValue)
	}
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		name, ok := protocol.JSONName(f)
		if !ok {
			continue
		}
		ts, err := g.tsType(f.Type, deps)
		if err != nil {
			return "", fmt.Errorf("%s.%s: %w", goName, f.Name, err)
		}
		if doc := g.docs.fields[goName+"."+f.Name]; doc != "" {
			b.WriteString(comment("  ", doc))
		}
		fmt.Fprintf(&b, "  %s: %s,\n", name, ts)
	}
	b.WriteString("}")
	return b.String(), nil
}

func (g *generator) tsType(t reflect.Type, deps map[string]bool) (string, error) {
	if name, ok := g.names[t]; ok {
		deps[name] = true
		return name, nil
	}
	switch {
	case t == timeType:
		return "string", nil // RFC 3339
	case t.Kind() == reflect.Pointer:
		inner, err := g.tsType(t.Elem(), deps)
		return inner + " | null", err
	case t.Kind() == reflect.Slice:
		inner, err := g.tsType(t.Elem(), deps)
		return "Array<" + inner + ">", err
	case t.Kind() == reflect.String:
		return "string", nil
	case t.Kind() == reflect.Bool:
		return "boolean", nil
	case slices.Contains([]reflect.Kind{reflect.Int, reflect.Int32, reflect.Int64, reflect.Uint32, reflect.Uint16, reflect.Float64}, t.Kind()):
		return "number", nil
	}
	return "", fmt.Errorf("no TypeScript type for %s", t)
}

// comment renders text as a doc comment, indented.
func comment(indent, text string) string {
	var b strings.Builder
	b.WriteString(indent + "/**\n")
	for _, line := range strings.Split(text, "\n") {
		b.WriteString(strings.TrimRight(indent+" * "+line, " ") + "\n")
	}
	b.WriteString(indent + " */\n")
	return b.String()
}
